import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const packageRoot = path.resolve(path.dirname(scriptPath), '..');
const repoRoot = path.resolve(packageRoot, '../..');
const tokenMapPath = path.join(repoRoot, 'design-tokens/compartment-token-map.json');
const tokenValuesPath = path.join(repoRoot, 'design-tokens/compartment-token-values.json');
const generatedCssPath = path.join(packageRoot, 'src/styles/tokens.generated.css');

const colorValuePattern = /^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/;

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, 'utf8'));
}

function isTokenMapEntry(value) {
  return value && typeof value === 'object' && typeof value.figma === 'string' && typeof value.css === 'string';
}

function collectTokenEntries(value, entries = []) {
  if (isTokenMapEntry(value)) {
    entries.push(value);
    return entries;
  }

  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    return entries;
  }

  for (const nestedValue of Object.values(value)) {
    collectTokenEntries(nestedValue, entries);
  }

  return entries;
}

function dedupeEntries(entries) {
  const byCssName = new Map();

  for (const entry of entries) {
    const previous = byCssName.get(entry.css);
    if (previous && previous.figma !== entry.figma) {
      throw new Error(`Conflicting mappings for ${entry.css}: ${previous.figma} and ${entry.figma}`);
    }
    byCssName.set(entry.css, entry);
  }

  return [...byCssName.values()].sort((a, b) => a.css.localeCompare(b.css));
}

function assertTokenValue(cssName, mode, value) {
  if (!colorValuePattern.test(value)) {
    throw new Error(`Expected ${cssName} ${mode} value to be a hex color, received ${JSON.stringify(value)}`);
  }
}

function renderBlock(selector, entries, values, mode) {
  const lines = [`${selector} {`];

  for (const entry of entries) {
    const token = values.tokens[entry.figma];
    if (!token) {
      throw new Error(`Missing Figma token value for ${entry.figma}`);
    }

    const value = token[mode];
    assertTokenValue(entry.css, mode, value);
    lines.push(`  ${entry.css}: ${value.toLowerCase()};`);
  }

  lines.push('}');
  return lines.join('\n');
}

function renderGeneratedCss(entries, values) {
  return `/* This file is generated by packages/console/scripts/generate-design-tokens.mjs. */
/* Source: design-tokens/compartment-token-map.json and design-tokens/compartment-token-values.json. */

${renderBlock(':root', entries, values, 'light')}

${renderBlock('.dark', entries, values, 'dark')}
`;
}

const tokenMap = await readJson(tokenMapPath);
const tokenValues = await readJson(tokenValuesPath);
const entries = dedupeEntries([
  ...collectTokenEntries(tokenMap.theme),
  ...collectTokenEntries(tokenMap.status),
  ...collectTokenEntries(tokenMap.opacity),
  ...collectTokenEntries(tokenMap.sidebar),
  ...collectTokenEntries(tokenMap.chart),
]);

const generatedCss = renderGeneratedCss(entries, tokenValues);

await mkdir(path.dirname(generatedCssPath), { recursive: true });
await writeFile(generatedCssPath, generatedCss);
