import { describe, expect, it } from 'vitest';
import { listCompartmentRolePermissions, listPermissionKeys, type CompartmentMembershipRole } from '../src';

describe('access contract role permissions', (): void => {
  it.each([
    ['viewer', ['project.read', 'app.route.access']],
    [
      'readonly',
      [
        'project.read',
        'app.route.access',
        'environment.read',
        'deployment.read',
        'deployment.logs.read',
        'deployment.inspect',
        'variable.metadata.read',
        'domain.read',
      ],
    ],
    [
      'deployer',
      [
        'project.read',
        'app.route.access',
        'environment.read',
        'deployment.read',
        'deployment.logs.read',
        'deployment.inspect',
        'variable.metadata.read',
        'domain.read',
        'organization.project.create',
        'deployment.create',
        'deployment.promote',
        'deployment.rollback',
        'project.lifecycle.write',
        'variable.value.read',
        'variable.write',
        'variable.local_run',
        'domain.write',
        'source.read',
      ],
    ],
    [
      'admin',
      [
        'project.read',
        'app.route.access',
        'environment.read',
        'deployment.read',
        'deployment.logs.read',
        'deployment.inspect',
        'variable.metadata.read',
        'domain.read',
        'organization.project.create',
        'deployment.create',
        'deployment.promote',
        'deployment.rollback',
        'project.lifecycle.write',
        'variable.value.read',
        'variable.write',
        'variable.local_run',
        'domain.write',
        'source.read',
        'project.settings.write',
        'project.archive',
        'project.delete',
        'organization.user.read',
        'organization.user.invite',
        'organization.user.block',
        'organization.user.remove',
        'organization.user.credentials.reset',
        'organization.group.read',
        'organization.group.manage',
        'organization.role.read',
        'organization.role.manage',
        'organization.auth.manage',
        'organization.settings.manage',
        'organization.audit.read',
        'source.manage',
      ],
    ],
  ] satisfies [CompartmentMembershipRole, string[]][])(
    'keeps the %s seeded permission set stable',
    (role: CompartmentMembershipRole, expectedPermissions: string[]): void => {
      expect(listCompartmentRolePermissions(role)).toEqual(expectedPermissions);
    },
  );

  it('keeps the permission catalog stable', (): void => {
    expect(listPermissionKeys()).toEqual([
      'organization.project.create',
      'organization.user.read',
      'organization.user.invite',
      'organization.user.block',
      'organization.user.remove',
      'organization.user.credentials.reset',
      'organization.group.read',
      'organization.group.manage',
      'organization.role.read',
      'organization.role.manage',
      'organization.auth.manage',
      'organization.settings.manage',
      'organization.audit.read',
      'project.read',
      'project.settings.write',
      'project.archive',
      'project.delete',
      'environment.read',
      'project.lifecycle.write',
      'deployment.read',
      'deployment.create',
      'deployment.promote',
      'deployment.rollback',
      'deployment.logs.read',
      'deployment.inspect',
      'variable.metadata.read',
      'variable.value.read',
      'variable.write',
      'variable.local_run',
      'domain.read',
      'domain.write',
      'source.read',
      'source.manage',
      'app.route.access',
    ]);
  });
});
